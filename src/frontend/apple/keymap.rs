//! macOS virtual key codes (HIToolbox kVK_*, physical ANSI positions) to PC
//! key names understood by keys::parse_named_key.

use super::keys::{self, InputKey};

pub fn mac_key(code: u16) -> Option<InputKey> {
    let name = match code {
        0x00 => "a",
        0x01 => "s",
        0x02 => "d",
        0x03 => "f",
        0x04 => "h",
        0x05 => "g",
        0x06 => "z",
        0x07 => "x",
        0x08 => "c",
        0x09 => "v",
        0x0b => "b",
        0x0c => "q",
        0x0d => "w",
        0x0e => "e",
        0x0f => "r",
        0x10 => "y",
        0x11 => "t",
        0x12 => "1",
        0x13 => "2",
        0x14 => "3",
        0x15 => "4",
        0x16 => "6",
        0x17 => "5",
        0x18 => "equal",
        0x19 => "9",
        0x1a => "7",
        0x1b => "minus",
        0x1c => "8",
        0x1d => "0",
        0x1e => "rightbracket",
        0x1f => "o",
        0x20 => "u",
        0x21 => "leftbracket",
        0x22 => "i",
        0x23 => "p",
        0x24 => "enter",
        0x25 => "l",
        0x26 => "j",
        0x27 => "apostrophe",
        0x28 => "k",
        0x29 => "semicolon",
        0x2a => "backslash",
        0x2b => "comma",
        0x2c => "slash",
        0x2d => "n",
        0x2e => "m",
        0x2f => "dot",
        0x30 => "tab",
        0x31 => "space",
        0x32 => "grave",
        0x33 => "backspace",
        0x35 => "escape",
        0x36 => "metaright",
        0x37 => "metaleft",
        0x38 => "leftshift",
        0x39 => "capslock",
        0x3a => "altleft",
        0x3b => "controlleft",
        0x3c => "rightshift",
        0x3d => "altright",
        0x3e => "controlright",
        0x41 => "numpaddecimal",
        0x43 => "numpadmultiply",
        0x45 => "numpadadd",
        // Keypad Clear sits where PC keyboards have Num Lock.
        0x47 => "numlock",
        0x4b => "numpaddivide",
        0x4c => "numpadenter",
        0x4e => "numpadsubtract",
        0x52 => "numpad0",
        0x53 => "numpad1",
        0x54 => "numpad2",
        0x55 => "numpad3",
        0x56 => "numpad4",
        0x57 => "numpad5",
        0x58 => "numpad6",
        0x59 => "numpad7",
        0x5b => "numpad8",
        0x5c => "numpad9",
        0x60 => "f5",
        0x61 => "f6",
        0x62 => "f7",
        0x63 => "f3",
        0x64 => "f8",
        0x65 => "f9",
        0x67 => "f11",
        0x6d => "f10",
        0x6f => "f12",
        // Help occupies the Insert position on extended keyboards.
        0x72 => "insert",
        0x73 => "home",
        0x74 => "pageup",
        0x75 => "delete",
        0x76 => "f4",
        0x77 => "end",
        0x78 => "f2",
        0x79 => "pagedown",
        0x7a => "f1",
        0x7b => "left",
        0x7c => "right",
        0x7d => "down",
        0x7e => "up",
        _ => return None,
    };
    keys::parse_named_key(name).ok()
}

#[cfg(test)]
mod tests {
    #[test]
    fn every_mapped_mac_key_names_a_pc_key() {
        let mapped = (0..0x80).filter_map(super::mac_key).count();
        // One per table entry: a misspelt name would map to nothing.
        assert_eq!(mapped, 100);
    }
}
