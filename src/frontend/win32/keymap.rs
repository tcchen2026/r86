//! Windows key messages carry the PC keyboard's set-1 scan code (lParam bits
//! 16-23, extended flag bit 24); the guest keyboard takes set-2 codes.

use super::keys::InputKey;

/// Set-2 make codes for set-1 codes 0x00..=0x58 (0 = no key). Extended keys
/// (E0 prefix) use the same code as their keypad or left-hand twin.
const SET2: [u8; 0x59] = [
    0x00, 0x76, 0x16, 0x1e, 0x26, 0x25, 0x2e, 0x36, // Esc 1-6
    0x3d, 0x3e, 0x46, 0x45, 0x4e, 0x55, 0x66, 0x0d, // 7-0 - = Backspace Tab
    0x15, 0x1d, 0x24, 0x2d, 0x2c, 0x35, 0x3c, 0x43, // Q W E R T Y U I
    0x44, 0x4d, 0x54, 0x5b, 0x5a, 0x14, 0x1c, 0x1b, // O P [ ] Enter Ctrl A S
    0x23, 0x2b, 0x34, 0x33, 0x3b, 0x42, 0x4b, 0x4c, // D F G H J K L ;
    0x52, 0x0e, 0x12, 0x5d, 0x1a, 0x22, 0x21, 0x2a, // ' ` LShift \ Z X C V
    0x32, 0x31, 0x3a, 0x41, 0x49, 0x4a, 0x59, 0x7c, // B N M , . / RShift KP*
    0x11, 0x29, 0x58, 0x05, 0x06, 0x04, 0x0c, 0x03, // Alt Space Caps F1-F5
    0x0b, 0x83, 0x0a, 0x01, 0x09, 0x77, 0x7e, 0x6c, // F6-F10 NumLock Scroll KP7
    0x75, 0x7d, 0x7b, 0x6b, 0x73, 0x74, 0x79, 0x69, // KP8 KP9 KP- KP4-6 KP+ KP1
    0x72, 0x7a, 0x70, 0x71, 0x00, 0x00, 0x61, 0x78, // KP2 KP3 KP0 KP. - - ISO\ F11
    0x07, // F12
];

/// The guest key for a WM_KEYDOWN/KEYUP lParam, if it has one.
pub fn key(lparam: isize) -> Option<InputKey> {
    let scan = ((lparam >> 16) & 0xff) as usize;
    let extended = lparam & (1 << 24) != 0;
    let code = match (scan, extended) {
        // Windows reports Num Lock as extended; it is a plain key.
        (0x45, _) => return Some(InputKey::Set2(false, 0x77)),
        (0x5b, true) => 0x1f, // left Windows
        (0x5c, true) => 0x27, // right Windows
        (0x5d, true) => 0x2f, // Menu
        _ => *SET2.get(scan)?,
    };
    (code != 0).then_some(InputKey::Set2(extended, code))
}
