#!/usr/bin/env python3
"""Generate Chisel B1 RTL; compare retirement/bus effects/traps with an RV oracle.

Deterministic instruction/memory tests plus an actual rustc RV32IM executable.
Use --synth for Yosys structural checks and --gowin for GW5A mapping.
Outputs stay in out/rtl. No globally installed tool or library is modified.
This is native-core validation, not guest x86/SMC integration or ISA certification.
"""
import argparse
from collections import Counter
import hashlib
import json
import os
from pathlib import Path
import random
import shutil
import struct
import subprocess

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
RTL = HERE.parent / "rtl"
OUT = HERE / "out/rtl"
SIMULATOR = ROOT / "target/release/r86chip-sim"
MASK = 0xffffffff
SIZE = 131072


def run(command, cwd=None, env=None):
    result = subprocess.run([str(x) for x in command], cwd=OUT if cwd is None else cwd, text=True,
                            stdout=subprocess.PIPE, stderr=subprocess.STDOUT, env=env)
    if result.returncode:
        raise RuntimeError(f"{command!r}:\n{result.stdout[-10000:]}")
    return result.stdout


def sources(banks):
    return [OUT / f"b{banks}/r86_core.sv", OUT / f"b{banks}/MulDiv.sv", RTL / "r86_regfile.v"]


def build():
    # Chisel's pinned artifact selects its matching firtool 1.146.0 through the
    # resolver. Do not accidentally use this machine's older PATH firtool.
    env = os.environ.copy()
    env.pop("CHISEL_FIRTOOL_PATH", None)
    log = run(["sbt", "-batch", *[
        f"runMain r86chip.Generate {b} {OUT / f'b{b}'}" for b in (1, 2)]], RTL, env)
    (OUT / "generation.log").write_text(log)
    for banks in (1, 2):
        out = OUT / f"b{banks}"
        for source in sources(banks)[:2]:
            assert source.read_text().startswith("// Generated by CIRCT firtool-1.146.0\n"), source
        # A generated file may contain multiple modules; the RAM style is a
        # synthesis-only parameter. Width, latch and combinational-loop warnings
        # remain errors. BANKS=1 legitimately drops unused bank/address bits.
        lint = run(["verilator", "--lint-only", "--top-module", "r86_core", "-Wall",
                    "-Wno-DECLFILENAME", "-Wno-UNUSEDPARAM", "-Wno-UNUSEDSIGNAL",
                    *sources(banks)])
        (out / "lint.log").write_text(lint)
        log = run(["verilator", "--binary", "--timing", "--top-module", "core_tb",
                   "-Wno-TIMESCALEMOD", "-j", "2", "--Mdir", out / "obj",
                   *sources(banks), RTL / "tests/core_tb.sv"])
        (out / "build.log").write_text(log)
        run(["iverilog", "-g2012", "-s", "core_tb", "-o", out / "core.vvp",
             *sources(banks), RTL / "tests/core_tb.sv"])
        # Four-state simulation exercises the actual RF wrapper separately:
        # same-edge forwarding, every address pair, bank tags, held operands.
        run(["iverilog", "-g2012", "-s", "regfile_tb", f"-Pregfile_tb.BANKS={banks}",
             "-o", out / "rf.vvp", RTL / "r86_regfile.v", RTL / "tests/regfile_tb.sv"])
        (out / "rf.log").write_text(run(["vvp", out / "rf.vvp"]))


def synthesize(banks, gowin, datadir, library, mapper):
    out = OUT / f"b{banks}"
    # Use the ordinary Verilog frontend, without enabling SystemVerilog. The
    # generated file suffix does not determine its required language features.
    read = "read_verilog " + " ".join(json.dumps(str(p)) for p in sources(banks)) + "\n"
    script = (read + "hierarchy -check -top r86_core\n"
              "synth -top r86_core -noabc\ncheck -assert\n"
              "select -assert-none t:$dlatch t:$_DLATCH_*\nstat\nwrite_json generic.json\n")
    (out / "generic.ys").write_text(script)
    run(["yosys", "-Q", "-T", "-l", "generic.log", "generic.ys"], out)
    if not gowin:
        return {"banks": banks, "generic_structure": "passed"}
    # Same local GW5A library/mapper repairs as the standalone RF experiment.
    synth = "synth_gowin -nowidelut"
    script = (read +
              f"read_verilog -specify -lib {json.dumps(str(datadir / 'gowin/cells_sim.v'))}\n"
              f"read_verilog -specify -lib {json.dumps(str(library))}\n"
              "hierarchy -check -top r86_core\n"
              f"{synth} -run flatten:map_ram -family gw5a -top r86_core -noiopads\n"
              "memory_libmap -lib +/gowin/lutrams.txt -lib +/gowin/brams.txt\n"
              f"techmap -map +/gowin/lutrams_map.v -map {json.dumps(str(mapper))}\n"
              f"{synth} -run map_ffram: -family gw5a -top r86_core -noiopads -json mapped.json\n"
              "check -assert\nstat\nwrite_verilog -noattr mapped.v\n")
    (out / "gowin.ys").write_text(script)
    run(["yosys", "-Q", "-T", "-l", "gowin.log", "gowin.ys"], out)
    module = json.loads((out / "mapped.json").read_text())["modules"]["r86_core"]
    cells = Counter(c["type"] for c in module["cells"].values())
    assert cells["SDPX9B"] == 2, cells
    return dict(banks=banks, generic_structure="passed",
                logic_lut1_to_lut4=sum(cells[f"LUT{i}"] for i in range(1, 5)),
                alu_carry_cells=cells["ALU"],
                flip_flops=sum(n for cell, n in cells.items() if cell.startswith("DFF")),
                block_ram_cells=cells["SDPX9B"], all_cells=dict(sorted(cells.items())))


def signed(x, bits=32):
    return (x & ((1 << (bits - 1)) - 1)) - (x & (1 << (bits - 1)))


def multiply_divide(op, a, b):
    # Python's unbounded integers and truncation toward zero are independent of
    # the RTL's bit-serial arithmetic algorithms.
    if op == 0:
        return a * b & MASK
    if op < 4:
        return ((signed(a) if op != 3 else a) *
                (signed(b) if op == 1 else b) >> 32) & MASK
    if b == 0:
        return a if op >= 6 else MASK
    x, y = (signed(a), signed(b)) if op in (4, 6) else (a, b)
    q = abs(x) // abs(y)
    if (x < 0) != (y < 0):
        q = -q
    return (x - q * y if op >= 6 else q) & MASK


class Fault(Exception):
    def __init__(self, cause, value):
        self.cause, self.value = cause, value & MASK


def reference(image, banks, fault_pc=-1):
    """Sequential ISA reference; deliberately has no pipeline/bus latency model."""
    mem = bytearray(image)
    regs = [[None] * 32 for _ in range(2)]
    regs[0][0] = regs[1][0] = 0
    bank, pc, runtime_return, guest_return, reason = 0, 0x1000, 0, 0, 0
    events = []
    flags = pending_flags = 0
    guest_maps = {}
    guest_fetch_maps = {}
    guest_base = guest_limit = 0
    guest_context = None
    guest_segments = [(0, 0, 0)] * 6
    service_vector, service_active = 0, False
    service_record = [0] * 4
    ea_registers, ea_info = None, MASK
    for _ in range(200000):
        old_bank = bank
        word = 0
        try:
            if pc & 3:
                raise Fault(0, pc)
            if pc + 4 > len(mem) or pc == fault_pc:
                raise Fault(1, pc)
            word = int.from_bytes(mem[pc:pc+4], "little")
            op, rd, f3 = word & 127, (word >> 7) & 31, (word >> 12) & 7
            r1, r2, f7 = (word >> 15) & 31, (word >> 20) & 31, word >> 25
            ii = signed(word >> 20, 12)
            si = signed((word >> 25) << 5 | (word >> 7) & 31, 12)
            next_pc = (pc + 4) & MASK
            dst_bank, value = bank, None

            def reg(index, which=old_bank):
                value = regs[which][index]
                assert value is not None, f"uninitialized x{index}, bank {which}, PC {pc:x}"
                return value

            def illegal():
                raise Fault(2, word)

            if op == 0x37:
                value = word & 0xfffff000
            elif op == 0x17:
                value = pc + (word & 0xfffff000)
            elif op == 0x6f:
                imm = ((word >> 31) << 20 | ((word >> 12) & 255) << 12 |
                       ((word >> 20) & 1) << 11 | ((word >> 21) & 1023) << 1)
                value, next_pc = pc + 4, (pc + signed(imm, 21)) & MASK
            elif op == 0x67:
                if f3:
                    illegal()
                value, next_pc = pc + 4, (reg(r1) + ii) & 0xfffffffe
            elif op == 0x63:
                a, b = reg(r1), reg(r2)
                tests = {0: a == b, 1: a != b, 4: signed(a) < signed(b),
                         5: signed(a) >= signed(b), 6: a < b, 7: a >= b}
                if f3 not in tests:
                    illegal()
                imm = ((word >> 31) << 12 | ((word >> 7) & 1) << 11 |
                       ((word >> 25) & 63) << 5 | ((word >> 8) & 15) << 1)
                if tests[f3]:
                    next_pc = (pc + signed(imm, 13)) & MASK
            elif op in (0x13, 0x33):
                a, b = reg(r1), (ii & MASK if op == 0x13 else reg(r2))
                if op == 0x33 and f7 == 1:
                    value = multiply_divide(f3, a, b)
                elif op == 0x33 and f7 == 16:
                    if f3 not in (2, 4, 6):
                        illegal()
                    value = a * (1 << (f3 // 2)) + b
                else:
                    if op == 0x33 and f7 != 0 and not (f7 == 32 and f3 in (0, 5)):
                        illegal()
                    if op == 0x13 and ((f3 == 1 and f7 != 0) or
                                                     (f3 == 5 and f7 not in (0, 32))):
                        illegal()
                    value = {
                        0: a - b if op == 0x33 and f7 == 32 else a + b,
                        1: a << (b & 31), 2: int(signed(a) < signed(b)),
                        3: int(a < b), 4: a ^ b,
                        5: (signed(a) if word & (1 << 30) else a) >> (b & 31),
                        6: a | b, 7: a & b,
                    }[f3]
            elif op in (0x03, 0x23):
                store = op == 0x23
                if f3 not in ((0, 1, 2) if store else (0, 1, 2, 4, 5)):
                    illegal()
                width = 1 << (f3 & 3)
                addr = (reg(r1) + (si if store else ii)) & MASK
                if addr & (width - 1):
                    raise Fault(6 if store else 4, addr)
                data = reg(r2) if store else 0
                strobes = ((1 << width)-1) << (addr & 3) if store else 0
                events.append(("D", addr & ~3, strobes, (data << ((addr & 3)*8)) & MASK))
                if addr + width > len(mem):
                    raise Fault(7 if store else 5, addr)
                if store:
                    mem[addr:addr+width] = (data & ((1 << (width*8))-1)).to_bytes(width, "little")
                    events.append(("S", addr & ~3, ((1 << width)-1) << (addr & 3),
                                   (data << ((addr & 3)*8)) & MASK))
                else:
                    value = int.from_bytes(mem[addr:addr+width], "little")
                    if f3 < 4:
                        value = signed(value, width*8)
            elif op == 0x0f:
                if f3 not in (0, 1):
                    illegal()
            elif op == 0x73:
                if word == 0x73:
                    raise Fault(11, 0)
                if word == 0x100073:
                    raise Fault(3, pc)
                illegal()
            elif op == 0x0b:
                if f3 < 4 and f7 & 64:
                    if f7 not in (64, 80) or (f7 & 16 and f3 < 2):
                        illegal()
                    # Use byte replacement, independently of RTL's mask/mux.
                    data = bytearray(reg(r1).to_bytes(4, "little"))
                    source = reg(r2).to_bytes(4, "little")
                    width, start, src = (4, 2, 1, 1)[f3], int(f3 == 3), int(bool(f7 & 16))
                    data[start:start+width] = source[src:src+width]
                    value = int.from_bytes(data, "little")
                elif f3 < 4:
                    kind = f7 & 7
                    if (f7 & ~0x3f or (f7 & 16 and f3 < 2)
                            or (f7 & 32 and kind not in (0, 5))
                            or (kind == 7 and (r2 or f7 & 48))):
                        illegal()
                    width = (32, 16, 8, 8)[f3]
                    mask, shift = (1 << width)-1, 8 if f3 == 3 else 0
                    original = reg(r1)
                    left = original >> shift & mask
                    right = reg(r2) >> (8 if f7 & 16 else 0) & mask
                    if kind == 7:
                        left, right = 0, left
                    ci = flags & 1 if kind in (2, 3) else 0
                    sub = kind in (3, 5, 7)
                    wide = left-right-ci if sub else left+right+ci
                    result = {1: left | right, 4: left & right, 6: left ^ right}.get(kind, wide) & mask
                    pending_flags = (int(result.bit_count() % 2 == 0) << 2 if width == 8 else
                                     int((result & 255).bit_count() % 2 == 0) << 2)
                    pending_flags |= int(result == 0) << 6 | (result >> (width-1)) << 7
                    if kind not in (1, 4, 6):
                        signed_result = (signed(left, width)-signed(right, width)-ci if sub else
                                         signed(left, width)+signed(right, width)+ci)
                        nibble = (left & 15)-(right & 15)-ci if sub else (left & 15)+(right & 15)+ci
                        pending_flags |= int(not 0 <= wide <= mask) | int(not 0 <= nibble <= 15) << 4
                        pending_flags |= int(not -(1 << (width-1)) <= signed_result < 1 << (width-1)) << 11
                    if f7 & 32:
                        pending_flags = pending_flags & ~1 | flags & 1
                    if f7 & 8:
                        flags = pending_flags
                    value = original & ~(mask << shift) | result << shift
                else:
                    if word >> 20 or (f3 == 4 and rd) or (f3 == 7 and r1 > 15):
                        illegal()
                    if f3 == 4:
                        flags = pending_flags = reg(r1) & 0x8d5
                    elif f3 == 5:
                        value = reg(r1) & ~0x8d5 | flags
                    elif f3 == 6:
                        flags, value = pending_flags, reg(r1)
                    else:
                        cf, pf, zf, sf, of = (bool(flags & (1 << n)) for n in (0, 2, 6, 7, 11))
                        value = int((of, cf, zf, cf or zf, sf, pf, sf != of, zf or sf != of)[r1 >> 1]
                                    != bool(r1 & 1))
            elif op == 0x2b:
                if f3 == 0:
                    mode = word >> 20
                    if mode >= 16 or mode % 4 == 3:
                        illegal()
                    address = reg(r1)
                    page, offset = divmod(address, 4096)
                    required = (1, 2, 4, 3)[mode // 4]
                    entry = (guest_fetch_maps if mode // 4 == 2 else guest_maps).get(
                        page % (4 if mode // 4 == 2 else 16))
                    value = MASK
                    if (entry is not None and entry[0] == page and
                            entry[2] & required == required and offset % (1 << (mode % 4)) == 0):
                        value = entry[1] + offset
                elif f3 == 1:
                    if rd or f7 > 1:
                        illegal()
                    address, payload = reg(r1), reg(r2)
                    if payload & (0xffb if f7 else 0xffc):
                        illegal()
                    page, offset = divmod(payload, 4096)
                    table = guest_fetch_maps if f7 else guest_maps
                    index = address // 4096 % (4 if f7 else 16)
                    table.pop(index, None)
                    if guest_base <= page * 4096 < guest_limit:
                        table[index] = (address // 4096, page * 4096, offset)
                elif f3 == 2:
                    if rd or word >> 20:
                        illegal()
                    guest_maps.pop(reg(r1) // 4096 % 16, None)
                    guest_fetch_maps.pop(reg(r1) // 4096 % 4, None)
                elif f3 == 3:
                    if rd or r1 or word >> 20:
                        illegal()
                    guest_maps.clear()
                    guest_fetch_maps.clear()
                elif f3 == 4:
                    if rd or f7:
                        illegal()
                    base, limit = reg(r1), reg(r2)
                    if base % 4096 or limit % 4096 or base > limit:
                        illegal()
                    guest_base, guest_limit = base, limit
                    guest_maps.clear()
                    guest_fetch_maps.clear()
                elif f3 == 5:
                    if rd or f7:
                        illegal()
                    context = (reg(r1), reg(r2))
                    if context[0] >= 64:
                        illegal()
                    if context != guest_context:
                        guest_maps.clear()
                        guest_fetch_maps.clear()
                        guest_segments = [(0, 0, 0)] * 6
                    guest_context = context
                elif f3 == 6:
                    if rd >= 6 or f7 >= 8:
                        illegal()
                    guest_segments[rd] = (reg(r1), reg(r2), f7)
                elif f7 == 0:
                    if rd or r2 or reg(r1) % 4:
                        illegal()
                    service_vector = reg(r1)
                elif f7 == 1:
                    if r2 or r1 >= 8:
                        illegal()
                    value = (service_record + list(guest_context or (0, 0)) +
                             [service_vector, int(service_active)])[r1]
                elif f7 == 2:
                    if rd or r2 or not service_active:
                        illegal()
                    next_pc = reg(r1) if r1 else service_record[0]
                    if next_pc % 4:
                        raise Fault(0, next_pc)
                    service_active = False
                else:
                    illegal()
            elif op == 0x5b:
                store, register_segment = bool(f3 & 4), bool(f7 & 64)
                seg = reg(r2) if register_segment else f7 % 8
                rmw, fetch, extra = (bool(f7 & n) for n in (8, 16, 32))
                unaligned_fetch = fetch and extra
                if (f3 % 4 == 3 or seg >= 6 or (register_segment and f7 % 8 != 0)
                        or (store and (rd or rmw or fetch or register_segment))
                        or (not store and ((not register_segment and r2) or (extra and not fetch)))
                        or (fetch and (seg != 1 or rmw))):
                    illegal()
                offset, width = reg(r1), 1 << (f3 % 4)
                required = 2 if store else 4 if fetch else 3 if rmw else 1
                base, limit, rights = guest_segments[seg]
                linear = (base + offset) & MASK
                page, page_offset = divmod(linear, 4096)
                mapping = (guest_fetch_maps if fetch else guest_maps).get(page % (4 if fetch else 16))
                if guest_context is None or guest_context[0] & 9 != 1:
                    service_reason = 1
                elif rights & required != required or offset + width - 1 > limit:
                    service_reason = 2
                elif (page_offset + width > 4096 if unaligned_fetch else linear % width):
                    service_reason = 3
                elif mapping is None or mapping[0] != page or mapping[2] & required != required:
                    service_reason = 4
                else:
                    service_reason = 0
                if service_reason:
                    if not service_vector or service_active:
                        raise Fault(12, offset)
                    service_record = [pc, offset, word, service_reason]
                    service_active, next_pc = True, service_vector
                else:
                    addr = mapping[1] + page_offset
                    data = reg(r2) if store else 0
                    strobes = ((1 << width) - 1) << (addr % 4) if store else 0
                    bus_data = (data << (addr % 4 * 8)) & MASK
                    events.append(("D", addr & ~3, strobes, bus_data))
                    if addr >= len(mem):
                        raise Fault(7 if store else 5, addr)
                    if unaligned_fetch and addr % 4 + width > 4:
                        events.append(("D", (addr & ~3) + 4, 0, 0))
                    if addr + width > len(mem):
                        raise Fault(7 if store else 5, addr)
                    if store:
                        mem[addr:addr+width] = (data & ((1 << (width*8))-1)).to_bytes(width, "little")
                        events.append(("S", addr & ~3, strobes, bus_data))
                        if extra:
                            flags = pending_flags
                    else:
                        value = int.from_bytes(mem[addr:addr+width], "little")
            elif op == 0x7b:
                if f3 == 0:
                    raw, start = reg(r1), reg(r2)
                    if f7 or raw > 255 or raw >> 6 == 3:
                        illegal()

                    def ea_read(addr, width):
                        # Bus events express this RTL's fixed RAM read phases;
                        # the gold ISS independently checks final architecture.
                        events.append(("D", addr & ~3, 0, 0))
                        if addr >= len(mem):
                            raise Fault(5, addr)
                        if addr % 4 + width > 4:
                            events.append(("D", (addr & ~3) + 4, 0, 0))
                        if addr + width > len(mem):
                            raise Fault(5, addr)
                        return int.from_bytes(mem[addr:addr+width], "little")

                    def ea_code(offset, width):
                        base, limit, rights = guest_segments[1]
                        linear, first = (base + offset) & MASK, (base + start) & MASK
                        page, within = divmod(linear, 4096)
                        mapping = guest_fetch_maps.get(page % 4)
                        if (not rights & 4 or offset < start or offset + width - 1 > limit
                                or linear // 4096 != first // 4096 or within + width > 4096
                                or mapping is None or mapping[0] != page or not mapping[2] & 4):
                            return None
                        return ea_read(mapping[1] + within, width)

                    def calculate_ea():
                        if ea_registers is None or guest_context is None or guest_context[0] & 9 != 1:
                            return None
                        mode, rm = raw >> 6, raw & 7
                        used, base, index, scale = 0, rm, None, 0
                        if rm == 4:
                            sib = ea_code(start, 1)
                            if sib is None:
                                return None
                            used, base, scale = 1, sib & 7, sib >> 6
                            if sib >> 3 & 7 != 4:
                                index = sib >> 3 & 7
                        if mode == 0 and base == 5:
                            base = None
                        width = 1 if mode == 1 else 4 if mode == 2 or base is None else 0
                        offset = 0
                        if width:
                            offset = ea_code((start + used) & MASK, width)
                            if offset is None:
                                return None
                            if width == 1:
                                offset = signed(offset, 8)
                            used += width
                        if base is not None:
                            offset += ea_read(ea_registers + base*4, 4)
                        if index is not None:
                            offset += ea_read(ea_registers + index*4, 4) << scale
                        return offset & MASK, used*2 | int(base in (4, 5))

                    calculated = calculate_ea()
                    if calculated is None:
                        ea_info = MASK
                    else:
                        value, ea_info = calculated
                elif f3 == 1:
                    if r1 or word >> 20:
                        illegal()
                    value = ea_info
                elif f3 == 2:
                    address = reg(r1)
                    if rd or word >> 20 or address % 4 or address > 0xffffffe0:
                        illegal()
                    ea_registers, ea_info = address, MASK
                elif f3 == 3:
                    if r1 >= 16 or r2:
                        illegal()
                    cf, pf, zf, sf, of = (bool(flags & (1 << n)) for n in (0, 2, 6, 7, 11))
                    take = (of, cf, zf, cf or zf, sf, pf, sf != of, zf or sf != of)[r1 >> 1]
                    if take != bool(r1 & 1):
                        imm = ((word >> 31) << 12 | ((word >> 7) & 1) << 11 |
                               ((word >> 25) & 63) << 5 | ((word >> 8) & 15) << 1)
                        next_pc = (pc + signed(imm, 13)) & MASK
                elif banks != 2:
                    illegal()
                elif f3 == 4 and bank == 0 and rd == 0 and word >> 20 == 0:
                    runtime_return, next_pc, bank = pc + 4, reg(r1), 1
                elif f3 == 5 and bank == 1 and rd == 0 and r1 == 0:
                    guest_return, reason, next_pc, bank = pc + 4, word >> 20, runtime_return, 0
                    pending_flags = flags
                elif f3 == 6 and bank == 0 and r2 == 0:
                    if f7 == 0:
                        value = reg(r1, 1)
                    elif f7 == 1 and r1 < 3:
                        value = (reason, guest_return, 0x42310008)[r1]
                    else:
                        illegal()
                elif f3 == 7 and bank == 0 and r2 == 0 and f7 == 0:
                    value, dst_bank = reg(r1), 1
                else:
                    illegal()
            else:
                illegal()
            if next_pc & 3:
                raise Fault(0, next_pc)
            write = value is not None and rd != 0
            if write:
                value &= MASK
                regs[dst_bank][rd] = value
            events.append(("R", pc, word, old_bank, int(write),
                           dst_bank*32 + rd if write else 0, value if write else 0))
            pc = next_pc
        except Fault as fault:
            events.append(("T", pc, fault.cause, fault.value))
            return events, mem
    raise RuntimeError("reference timeout")


def compare_iss(image_path, events, memory):
    ram_path = image_path.with_suffix(".bin")
    # Native runner consumes the initial flat image, not the final memory.
    observed = json.loads(run([SIMULATOR, "native", ram_path]))
    registers = [[None] * 32 for _ in range(2)]
    registers[0][0] = registers[1][0] = 0
    for event in events:
        if event[0] == "R" and event[4]:
            registers[event[5] // 32][event[5] % 32] = event[6]
    for bank in range(2):
        for reg, value in enumerate(registers[bank]):
            if value is not None:
                assert observed["registers"][bank][reg] == value, (image_path, bank, reg, observed)
    trap = events[-1]
    assert trap[0] == "T" and (observed["pc"], observed["cause"], observed["value"]) == trap[1:]
    digest = 0xcbf29ce484222325
    for byte in memory:
        digest = ((digest ^ byte) * 0x100000001b3) & ((1 << 64)-1)
    assert observed["ram_fnv64"] == f"{digest:016x}", image_path
    assert observed["retired_native"] == sum(e[0] == "R" for e in events), image_path


def it(op, rd, f3, r1, imm):
    return (imm & 4095) << 20 | r1 << 15 | f3 << 12 | rd << 7 | op


def rt(rd, f3, r1, r2, f7=0):
    return f7 << 25 | r2 << 20 | r1 << 15 | f3 << 12 | rd << 7 | 0x33


def st(f3, r1, r2, imm):
    return ((imm & 4095) >> 5) << 25 | r2 << 20 | r1 << 15 | f3 << 12 | (imm & 31) << 7 | 0x23


def br(f3, r1, r2, off):
    return (((off >> 12) & 1) << 31 | ((off >> 5) & 63) << 25 | r2 << 20 |
            r1 << 15 | f3 << 12 | ((off >> 1) & 15) << 8 | ((off >> 11) & 1) << 7 | 0x63)


def xjcc(cc, off):
    return (br(3, cc, 0, off) & ~127) | 0x7b


def jal(rd, off):
    return (((off >> 20) & 1) << 31 | ((off >> 1) & 1023) << 21 |
            ((off >> 11) & 1) << 20 | ((off >> 12) & 255) << 12 | rd << 7 | 0x6f)


class Program:
    def __init__(self):
        self.mem = bytearray(SIZE)
        self.pc = 0x1000

    def emit(self, *words):
        for word in words:
            struct.pack_into("<I", self.mem, self.pc, word & MASK)
            self.pc += 4

    def li(self, rd, value):
        high = ((value + 0x800) >> 12) & 0xfffff
        self.emit(high << 12 | rd << 7 | 0x37, it(0x13, rd, 0, rd, value))

    def finish(self):
        self.emit(0x100073)
        return bytes(self.mem)


def tlb_cases():
    """Real native probe/service code, qualified before RTL against the Rust ISS.

    The short refill stubs install known fixture RAM mappings. They are not a
    second x86 walker or evidence of whole-machine TLB integration.
    """
    def region(p, base=0x10000, limit=0x18000):
        p.li(1, base); p.li(2, limit); p.emit(it(0x2b, 0, 4, 1, 2))

    def fill_view(p, linear, page_rights, fetch=False):
        p.li(1, linear); p.li(2, page_rights)
        p.emit(it(0x2b, 0, 1, 1, 2 | (32 if fetch else 0)))

    def fill(p, linear, page_rights):
        fill_view(p, linear, page_rights & ~4)
        fill_view(p, linear, page_rights & ~3, True)

    result = []
    p = Program()
    region(p, 0x80000000, 0x80010000)
    for rights in range(8):
        fill(p, 0xfffff000, 0x80000000 | rights)
        for intent in range(4):
            for size in range(3):
                for off in (0, 1, 2, 3, 0xffc, 0xffd, 0xffe, 0xfff):
                    p.li(1, 0xfffff000 + off)
                    p.emit(it(0x2b, 1, 0, 1, intent * 4 + size))
    result.append(("xtlb_permissions", p.finish(), -1, False))

    p = Program()
    fill(p, 0x4000, 0x10007) # reset has an empty window
    p.emit(it(0x2b, 3, 0, 1, 2))
    region(p)
    for forbidden in (0, 0x1000, 0xf000, 0x18000, 0xfffff000):
        fill(p, 0x4000, 0x10007)
        p.emit(it(0x2b, 3, 0, 1, 2))
        fill(p, 0x4000, forbidden | 7)
        p.emit(it(0x2b, 4, 0, 1, 2))
    for page in range(16):
        fill(p, page << 12, 0x10007)
    p.li(1, 0x104000); p.emit(it(0x2b, 0, 2, 1, 0)) # evict colliding slot 4
    for page in range(16):
        p.li(1, page << 12); p.emit(it(0x2b, 3, 0, 1, 2))
    p.emit(it(0x0f, 0, 1, 0, 0)) # FENCE.I must preserve guest mappings
    p.emit(it(0x2b, 3, 0, 1, 2))
    region(p) # configuring identical bounds still flushes
    p.li(1, 0xf000); p.emit(it(0x2b, 3, 0, 1, 2))
    region(p, 0x18000, 0x18000)
    fill(p, 0x4000, 0x18007); p.emit(it(0x2b, 3, 0, 1, 2))
    # Independent native code can still read private firmware RAM.
    p.li(1, 0x800); p.emit(it(0x03, 3, 2, 1, 0))
    struct.pack_into("<I", p.mem, 0x800, 0xabcdef12)
    result.append(("xtlb_window", p.finish(), -1, False))

    p = Program()
    region(p)
    fill(p, 0x4000, 0x10007)
    p.li(31, 0x4000); p.emit(it(0x7b, 0, 4, 31, 0))
    p.li(1, 0x5000); p.emit(it(0x2b, 3, 0, 1, 2))
    p.emit(it(0x2b, 3, 0, 1, 6))
    p.finish(); p.pc = 0x4000
    p.li(1, 0x4000); p.emit(it(0x2b, 3, 0, 1, 2))
    p.emit(it(0x2b, 0, 3, 0, 0))
    fill(p, 0x5000, 0x10005) # physical code watch denies writes through aliases
    p.emit(it(0x7b, 0, 5, 0, 0))
    result.append(("xtlb_banks", bytes(p.mem), -1, True))

    p = Program()
    region(p)
    # Independent D/I capacity, different native backing, explicit revocation.
    def probe_views(linear):
        p.li(1, linear)
        p.emit(it(0x2b, 5, 0, 1, 2), it(0x2b, 6, 0, 1, 10))
    fill_view(p, 0x4000, 0x10003)
    fill_view(p, 0x4000, 0x11004, True)
    probe_views(0x4004)
    fill_view(p, 0x14000, 0x12003)
    probe_views(0x4004); probe_views(0x14004)
    fill_view(p, 0x8000, 0x13004, True)
    probe_views(0x4004); probe_views(0x14004); probe_views(0x8004)
    p.li(1, 0x14000); p.emit(it(0x2b, 0, 2, 1, 0))
    probe_views(0x14004); probe_views(0x8004)
    fill(p, 0x4000, 0x10007)
    fill_view(p, 0x4000, 0x18004, True)
    probe_views(0x4004)
    fill_view(p, 0x4000, 0x11004, True)
    fill_view(p, 0x4000, 0x10000)
    probe_views(0x4004)
    for operation in (3, 4, 5):
        fill(p, 0x4000, 0x10007)
        if operation == 3:
            p.emit(it(0x2b, 0, 3, 0, 0))
        elif operation == 4:
            region(p)
        else:
            p.li(1, 1); p.emit(it(0x2b, 0, 5, 1, 0))
        probe_views(0x4004)
    result.append(("xtlb_split_views", p.finish(), -1, False))

    p = Program()
    region(p)
    p.li(10, 0x4004); p.li(31, MASK); p.li(7, 0); p.li(8, 1)
    p.emit(it(0x0b, 0, 4, 0, 0))
    # Each of two accesses executes the same probe. The first branches into
    # genuine RV service code; the second hits. No host callback fills the TLB.
    for _ in range(2):
        p.emit(it(0x2b, 5, 0, 10, 14), br(1, 5, 31, 24))
        p.li(2, 0x10003)
        p.emit(it(0x2b, 0, 1, 10, 2), it(0x13, 7, 0, 7, 1), jal(0, -24))
        p.emit(it(0x03, 6, 2, 5, 0))
        p.emit(0x0b | 6 << 7 | 6 << 15 | 8 << 20) # staged ADD
        p.emit(st(2, 5, 6, 0), it(0x0b, 0, 6, 0, 0))
    p.emit(it(0x0b, 9, 5, 0, 0))
    struct.pack_into("<I", p.mem, 0x10004, 0xfffffffe)
    result.append(("xtlb_software_refill_rmw", p.finish(), -1, False))

    bad = [
        (it(0x2b, 3, 0, 1, 3), 0x10000, 0x18000),
        (it(0x2b, 3, 0, 1, 16), 0x10000, 0x18000),
        (it(0x2b, 3, 1, 1, 2), 0x10000, 0x18000),
        (it(0x2b, 0, 1, 1, 66), 0x10000, 0x18000),
        (it(0x2b, 0, 1, 1, 2), 0x10000, 0x10004),
        (it(0x2b, 0, 1, 1, 34), 0x10000, 0x10001),
        (it(0x2b, 0, 1, 1, 34), 0x10000, 0x10002),
        (it(0x2b, 0, 1, 1, 34), 0x10000, 0x10008),
        (it(0x2b, 0, 1, 1, 2), 0x10000, 0x10008),
        (it(0x2b, 0, 2, 1, 1), 0x10000, 0x18000),
        (it(0x2b, 0, 3, 1, 0), 0x10000, 0x18000),
        (it(0x2b, 3, 4, 1, 2), 0x10000, 0x18000),
        (it(0x2b, 0, 4, 1, 34), 0x10000, 0x18000),
        (it(0x2b, 0, 4, 1, 2), 0x10001, 0x18000),
        (it(0x2b, 0, 4, 1, 2), 0x10000, 0x18001),
        (it(0x2b, 0, 4, 1, 2), 0xfffff000, 0),
    ]
    for n, (instruction, a, b) in enumerate(bad):
        p = Program()
        region(p); fill(p, 0x4000, 0x10007)
        p.li(1, a); p.li(2, b); p.emit(instruction)
        result.append((f"xtlb_illegal_{n}", p.finish(), -1, False))
    return result


def guest_memory_cases():
    """Same native images exercise guest hits, rejection and software services.

    Refill bodies are deliberately small RAM-policy fixtures. They count as RV
    work but do not claim to implement the x86 walker or full interpreter ABI.
    """
    def custom(op, f, d=0, a=0, b=0, k=0):
        return op | d << 7 | f << 12 | a << 15 | b << 20 | k << 25

    def config(p, f, a, b, d=0, k=0):
        p.li(1, a); p.li(2, b); p.emit(custom(0x2b, f, d, 1, 2, k))

    def segment(p, n=3, base=0, limit=MASK, rights=7):
        config(p, 6, base, limit, n, rights)

    def fill(p, rights=7, page=0x10000):
        config(p, 1, 0x4000, page | (rights & 3))
        config(p, 1, 0x4000, page | (rights & 4), k=1)

    def setup():
        p = Program()
        config(p, 4, 0x10000, 0x18000)
        config(p, 5, 0x37, 17)
        for n in range(6):
            segment(p, n)
        fill(p)
        p.li(3, 0x4004); p.li(4, 0xa1b2c3d4); p.li(5, 0xdeadbeef)
        p.li(6, 0x80); p.emit(custom(0x0b, 4, a=6))
        p.li(7, MASK); p.li(8, 1); p.emit(custom(0x0b, 0, 9, 7, 8))
        struct.pack_into("<I", p.mem, 0x10004, 0x89abcdef)
        return p

    def vector(p):
        p.li(1, 0xf000); p.emit(custom(0x2b, 7, a=1))

    def finish_service(p, name, handler, bank_only=False):
        p.finish()
        assert p.pc < 0xf000
        p.pc = 0xf000
        for s in range(8):
            p.emit(custom(0x2b, 7, 20+s, s, 0, 1))
        handler(p)
        return name, bytes(p.mem), -1, bank_only

    def skip(p):
        # Explicit continuation is used only to observe rejected fixture ops;
        # a real interpreter must complete semantics/deliver a guest exception.
        p.emit(it(0x13, 20, 0, 20, 4), custom(0x2b, 7, a=20, k=2))

    result = []
    p = setup()
    p.li(10, 0x8004); p.emit(it(0x03, 11, 2, 10, 0))
    struct.pack_into("<I", p.mem, 0x8004, 0x12345678)
    for n in range(6):
        # Nonflat bases, including an aligned linear address from an unaligned
        # offset, use the segment selected in this instruction, not an RV mode.
        segment(p, n, 0x1001, 0x3006)
        p.li(3, 0x3003)
        for width in range(3):
            p.emit(custom(0x5b, width, 5, 3, k=n), custom(0x5b, 4+width, a=3, b=4, k=n))
    p.emit(custom(0x5b, 2, 0, 3, k=5), custom(0x5b, 2, 3, 3, k=5))
    p.emit(custom(0x0b, 5, 12))
    result.append(("xguest_views_widths", p.finish(), -1, False))

    p = setup()
    for n in range(6):
        segment(p, n, 0x1001, 0x3006)
        for width in range(3):
            for destination in (0, 3, 4, 5):
                p.li(3, 0x3003); p.li(4, n)
                p.emit(custom(0x5b, width, destination, 3, 4, 64))
    result.append(("xguest_register_segment", p.finish(), -1, False))

    for selector in (6, 7, 8, 0x103, MASK):
        p = setup(); vector(p); p.li(4, selector)
        p.emit(custom(0x5b, 2, 5, 3, 4, 64))
        result.append((f"xguest_bad_selector_{selector:x}", p.finish(), -1, False))

    p = setup(); vector(p)
    for n, intent, rights in ((3, 0, 1), (3, 8, 1), (3, 8, 3), (1, 16, 1), (1, 16, 4)):
        fill(p, rights)
        p.li(4, n); p.li(31, 0)
        p.emit(custom(0x5b, 2, 5, 3, 4, 64 | intent))
    p.finish()
    p.pc = 0xf000
    p.emit(custom(0x2b, 7, 31, k=1), it(0x13, 31, 0, 31, 4), custom(0x2b, 7, a=31, k=2))
    result.append(("xguest_inline_service", bytes(p.mem), -1, False))

    p = setup()
    config(p, 1, 0x5000, 0x10003)
    p.emit(custom(0x5b, 2, 5, 3, k=17))
    p.li(10, 0x5004); p.emit(custom(0x5b, 6, a=10, b=4, k=3))
    p.emit(custom(0x5b, 2, 5, 3, k=17))
    p.li(10, 0x10004); p.li(4, 0x90909090); p.emit(st(2, 10, 4, 0))
    p.emit(custom(0x5b, 2, 5, 3, k=17))
    result.append(("xguest_fresh_fetch_alias", p.finish(), -1, False))

    p = setup()
    fill(p, rights=4)  # Execute-only proof: .U must not need/borrow data rights.
    segment(p, 1, base=1, rights=4)
    p.mem[0x10000:0x10008] = bytes.fromhex("1837567594b3d2f1")
    for width in range(3):
        for lane in range(4):
            for dynamic in (False, True):
                for destination in (0, 3, 4, 5):
                    p.li(3, 0x4000 + lane - 1); p.li(4, 1); p.li(5, 0xdeadbeef)
                    p.emit(custom(0x5b, width, destination, 3,
                                  4 if dynamic else 0, 112 if dynamic else 49))
    p.emit(custom(0x0b, 5, 12), custom(0x0b, 6, 13), custom(0x0b, 5, 14))
    result.append(("xguest_fetch_u_lanes", p.finish(), -1, False))

    p = setup()
    p.li(3, 0x4003); p.emit(custom(0x5b, 2, 5, 3, k=49))
    p.li(10, 0x10004); p.li(4, 0x76543210); p.emit(st(2, 10, 4, 0))
    p.emit(custom(0x5b, 2, 6, 3, k=49))  # Fresh bytes, no native FENCE.I.
    p.li(10, 0x4004); p.li(4, 0x89abcdef)
    p.emit(custom(0x5b, 6, a=10, b=4, k=3), custom(0x5b, 2, 7, 3, k=49))
    result.append(("xguest_fetch_u_fresh", p.finish(), -1, False))

    p = setup(); vector(p)
    for base, limit, offset, width, control, rights, mapped in (
            (0, 0x4006, 0x4003, 2, 0x37, 4, 4),  # Exact segment endpoint.
            (0, 0x4005, 0x4003, 2, 0x37, 4, 4),  # Segment before span/TLB.
            (0, MASK, 0x4ffc, 2, 0x37, 4, 4),
            (0, MASK, 0x4ffd, 2, 0x37, 4, 4),  # Both pages mapped, still service.
            (0, MASK, 0x4fff, 1, 0x37, 4, 4),
            (1, MASK, 0x4ffb, 2, 0x37, 4, 4),  # Qualify the LINEAR page end.
            (1, MASK, 0x4ffc, 2, 0x37, 4, 4),
            (0, MASK, 0xfffffffe, 2, 0x37, 4, 0),  # Widened segment end.
            (0, MASK, 0x4fff, 2, 0, 0, 0),     # Context precedes all else.
            (0, 0x4000, 0x4fff, 2, 0x37, 4, 0),
            (0, MASK, 0x4fff, 2, 0x37, 4, 0),  # Span before missing proof.
            (0, MASK, 0x4003, 2, 0x37, 4, 0),
            (0, MASK, 0x4003, 2, 0x37, 1, 4)):
        config(p, 5, control, 17)
        segment(p, 1, base, limit, rights)
        fill(p, mapped)
        config(p, 1, 0x5000, 0x11004, k=1)
        p.li(3, offset); p.emit(custom(0x5b, width, 5, 3, k=49))
    result.append(finish_service(p, "xguest_fetch_u_rejections", skip))

    # Truncate actual RAM at a word boundary, so both the gold ISS and bus RTL
    # see the same failure. The mapping deliberately promises an absent page
    # tail: native access fault, not an x86 page fault or software service.
    for width, lane in ((1, 3), (2, 1), (2, 2), (2, 3), (2, 4)):
        for destination in (0, 3, 5):
            p = setup(); vector(p)
            p.mem[0x10000:0x10004] = bytes.fromhex("18375675")
            p.li(3, 0x4000 + lane)
            p.emit(custom(0x5b, width, destination, 3, k=49))
            result.append((f"xguest_fetch_u_bus_fault_{width}_{lane}_{destination}",
                           p.finish()[:0x10004], -1, False))

    p = Program()
    config(p, 4, 0x10000, 0x18000); segment(p); fill(p)
    config(p, 5, 0, 0)
    p.li(3, 0x4004); p.emit(it(0x2b, 5, 0, 3, 2))
    result.append(("xguest_first_context", p.finish(), -1, False))

    p = setup(); vector(p)
    for rights in range(8):
        for page_rights in range(8):
            fill(p, page_rights)
            for intent in range(4):
                seg = 1 if intent == 2 else 3
                segment(p, seg, rights=rights)
                f, d, b = (6, 0, 4) if intent == 1 else (2, 5, 0)
                p.emit(custom(0x5b, f, d, 3, b, seg | (0, 0, 16, 8)[intent]))
    result.append(finish_service(p, "xguest_permissions", skip))

    p = setup(); vector(p)
    for ctl, token in ((0x37, 17), (0x33, 17), (0x37, 18), (1, 17), (0, 17), (9, 17)):
        config(p, 5, ctl, token)
        p.emit(custom(0x5b, 2, 5, 3, k=3))
        fill(p)
        p.emit(custom(0x5b, 2, 5, 3, k=3))
        segment(p)
        p.emit(custom(0x5b, 2, 5, 3, k=3))
        config(p, 5, ctl, token)  # identical context must preserve new proofs
        p.emit(custom(0x5b, 2, 5, 3, k=3))
    result.append(finish_service(p, "xguest_context", skip))

    p = setup(); vector(p)
    for base, limit, offset in ((0, 0x4007, 0x4004), (0, 0x4006, 0x4004),
                                (0, MASK, 0xfffffffe), (0, 0x4004, 0x4003),
                                (0, MASK, 0x4003), (0, MASK, 0x5000),
                                (0xffffc000, MASK, 0x8004)):
        segment(p, base=base, limit=limit)
        p.li(3, offset); p.emit(custom(0x5b, 2, 0, 3, k=3))
    result.append(finish_service(p, "xguest_limits_wrap", skip))

    p = setup(); vector(p)
    p.emit(custom(0x2b, 3))
    for _ in range(2):
        p.emit(custom(0x5b, 2, 5, 3, k=3 | 8), custom(0x0b, 0, 9, 5, 8))
        p.emit(custom(0x2b, 3), custom(0x5b, 6, a=3, b=9, k=3 | 32))
        p.emit(custom(0x0b, 5, 10))
    def refill(p):
        p.li(28, 0x9000); p.emit(it(0x03, 29, 2, 28, 0))
        p.emit(custom(0x2b, 1, a=21, b=29), custom(0x2b, 7, k=2))
    struct.pack_into("<I", p.mem, 0x9000, 0x10003)
    result.append(finish_service(p, "xguest_refill_store_commit", refill))

    # The same unconfigured access must never turn into native address zero.
    for nested in (False, True):
        p = setup()
        p.emit(custom(0x2b, 3))
        if nested:
            vector(p)
        p.emit(custom(0x5b, 2, 0, 3, k=3))
        result.append(finish_service(p, f"xguest_unhandled_{int(nested)}",
            lambda p: p.emit(custom(0x5b, 2, 0, 3, k=3))))

    for width in range(3):
        for store in (False, True):
            p = setup(); vector(p)
            config(p, 4, 0x20000, 0x21000); fill(p, page=0x20000)
            p.emit(custom(0x5b, width + 4*store, 0 if store else 5, 3,
                          4 if store else 0, 35 if store else 3))
            result.append((f"xguest_bus_fault_{width}_{int(store)}", p.finish(), -1, False))

    for target in (0x8002, 0x8000, SIZE):
        p = setup(); vector(p); p.emit(custom(0x2b, 3), custom(0x5b, 2, 5, 3, k=3))
        struct.pack_into("<I", p.mem, 0x8000, 0x100073)
        def explicit_return(p, target=target):
            p.li(28, target); p.emit(custom(0x2b, 7, a=28, k=2))
        result.append(finish_service(p, f"xguest_return_{target:x}", explicit_return))

    bad = [custom(0x2b, 5, 1), custom(0x2b, 5, k=1),
           custom(0x2b, 6, 6), custom(0x2b, 6, k=8),
           custom(0x2b, 7, 1), custom(0x2b, 7, b=1),
           custom(0x2b, 7, 5, 8, k=1), custom(0x2b, 7, 5, b=1, k=1),
           custom(0x2b, 7, k=2), custom(0x2b, 7, k=3),
           custom(0x5b, 2, 5, 3, 1, 3), custom(0x5b, 6, 5, 3, 4, 3)]
    for f, k in ((3, 3), (7, 3), (2, 6), (2, 7), (2, 67), (6, 11),
                 (6, 19), (2, 35), (2, 19), (2, 25), (2, 51), (2, 57), (6, 49)):
        bad.append(custom(0x5b, f, 0 if f & 4 else 5, 3, 4 if f & 4 else 0, k))
    for n, word in enumerate(bad):
        p = setup(); p.emit(word)
        result.append((f"xguest_illegal_{n}", p.finish(), -1, False))
    for f, value in ((5, 64), (7, 0xf002)):
        p = setup(); p.li(1, value); p.emit(custom(0x2b, f, a=1))
        result.append((f"xguest_bad_value_{f}", p.finish(), -1, False))

    p = Program()
    p.emit(custom(0x2b, 7, 5, 4, k=1), custom(0x2b, 7, 6, 5, k=1))
    p.emit(custom(0x5b, 0, a=0))
    result.append(("xguest_reset", p.finish(), -1, False))

    p = setup(); vector(p)
    p.li(31, 0x4000); p.emit(it(0x7b, 0, 4, 31, 0)); p.finish()
    p.pc = 0x4000
    p.li(3, 0x4004); p.emit(custom(0x5b, 2, 5, 3, k=3), custom(0x2b, 3))
    p.emit(custom(0x5b, 2, 5, 3, k=3), it(0x7b, 0, 5, 0, 0))
    struct.pack_into("<I", p.mem, 0x9000, 0x10003)
    result.append(finish_service(p, "xguest_banks", refill, True))
    return result


def ea_cases():
    """Fresh-byte EA computations, with independent matrix/ordering expectations.

    These are native ISA probes, not a second x86 interpreter. The arithmetic
    matrix below checks the Python trace oracle before the same images run on
    the gold ISS and RTL, including four-state RAM and delayed responses.
    """
    def custom(op, f, d=0, a=0, b=0, k=0):
        return op | d << 7 | f << 12 | a << 15 | b << 20 | k << 25

    def config(p, f, a, b, d=0, k=0):
        p.li(1, a); p.li(2, b); p.emit(custom(0x2b, f, d, 1, 2, k))

    values = [0xfffffff0, 0x12345678, 0x10203040, 0x2468abcd,
              0x80808080, 0x87654321, 0x11111111, 0x77777777]

    def setup(pointer=0x8000, configure=True):
        p = Program()
        config(p, 4, 0x10000, 0x18000)
        config(p, 5, 0x37, 3)
        config(p, 6, 0x1001, MASK, 1, 4)
        config(p, 1, 0x4000, 0x10004, k=1)
        struct.pack_into("<8I", p.mem, 0x8000, *values)
        if configure:
            p.li(9, pointer); p.emit(custom(0x7b, 2, a=9))
        return p

    # Assert selected retirement results using values computed independently
    # of reference(). Then compare_iss checks the entire trace's final state.
    def expect(p, expected, word, value):
        expected[p.pc] = value & MASK
        p.emit(word)

    def calculate(p, expected, raw, start, value, info, destination=12):
        p.li(10, raw); p.li(11, start); p.li(12, 0xdeadbeef)
        if info == MASK:  # rejection preserves whichever rd was selected
            value = {0: 0, 10: raw, 11: start, 12: 0xdeadbeef}[destination]
        expect(p, expected, custom(0x7b, 0, destination, 10, 11),
               value if destination else 0)
        expect(p, expected, custom(0x7b, 1, 13), info)

    result = []

    def finish(name, p, expected, size=SIZE, bank_only=False, trap=None, reads=None):
        image = p.finish()[:size]
        trace, _ = reference(image, 2)
        for e in trace:
            if e[0] == "R" and e[1] in expected:
                # No destination write on rejection/x0: the gold tests also
                # inspect preserved registers. EAINFO is always observable.
                if e[4]:
                    assert e[6] == expected[e[1]], (name, e, expected[e[1]])
                del expected[e[1]]
        assert not expected, (name, expected)
        if trap is not None:
            assert trace[-1][2:] == trap, (name, trace[-1], trap)
        if reads is not None:
            assert [e[1] for e in trace if e[0] == "D"] == reads, (name, trace)
        result.append((name, image, -1, bank_only))

    matrix = [(mode, rm, sib, lane)
              for mode in range(3) for rm in range(8)
              for sib in (range(256) if rm == 4 else [0]) for lane in range(4)]
    for group in range(0, len(matrix), 128):
        p, expected = setup(), {}
        for n, (mode, rm, sib, lane) in enumerate(matrix[group:group+128]):
            base = sib % 8 if rm == 4 else rm
            absent = mode == 0 and base == 5
            index = sib // 8 % 8
            disp = -128 if mode == 1 else 0xfedcba98 if mode == 2 else 0x89abcdef if absent else 0
            width = 1 if mode == 1 else 4 if mode == 2 or absent else 0
            raw_bytes = (bytes([sib]) if rm == 4 else b"") + (disp & MASK).to_bytes(4, "little")[:width]
            offset = 8*n + lane
            p.mem[0x10000+offset:0x10000+offset+len(raw_bytes)] = raw_bytes
            value = (0 if absent else values[base]) + disp
            if rm == 4 and index != 4:
                value += values[index] * 2**(sib // 64)
            info = len(raw_bytes)*2 + int(not absent and base in (4, 5))
            calculate(p, expected, mode*64 | (n % 8)*8 | rm, 0x2fff+offset, value, info)
        assert p.pc < 0x8000
        finish(f"xea_matrix_{group//128}", p, expected)

    p, expected = setup(), {}
    for destination in (0, 10, 11, 12):
        # Native stores modify the bytes and source GPR array between calls.
        # No context change/flush is needed: there is no decoded-address cache.
        for sib, disp, ebp in ((0x24, 1, 200), (0x2d, 0x80, 300)):
            p.li(3, 0x10000); p.li(4, sib | disp << 8); p.emit(st(1, 3, 4, 0))
            p.li(3, 0x8014); p.li(4, ebp); p.emit(st(2, 3, 4, 0))
            value = values[4]+1 if sib == 0x24 else ebp*2-128
            calculate(p, expected, 0x44, 0x2fff, value, 5, destination)
    # Consecutive operations with no EAINFO/idle cycle in between must reset
    # the bounded data sequencer when the first one retires.
    p.li(10, 0); p.li(11, 0)
    expect(p, expected, custom(0x7b, 0, 12, 10, 11), values[0])
    expect(p, expected, custom(0x7b, 0, 12, 10, 11), values[0])
    expect(p, expected, custom(0x7b, 1, 13), 0)
    finish("xea_current_bytes_gprs_aliases", p, expected)

    p, expected = setup(pointer=0), {}
    struct.pack_into("<8I", p.mem, 0, *values)
    p.emit(custom(0x2b, 3))  # no X proof; zero-byte form still works
    config(p, 6, MASK, 0, 1, 0)
    calculate(p, expected, 0, MASK, values[0], 0)
    finish("xea_zero_pointer_no_code", p, expected, reads=[0])

    for condition in range(10):
        p, expected = setup(pointer=0x30000, configure=condition != 0), {}
        start = 0x3000
        p.mem[0x10001:0x10006] = bytes([0x24, 1, 2, 3, 4])
        if condition == 1:
            config(p, 5, 0, 3)  # real mode
        elif condition == 2:
            config(p, 5, 9, 3)  # v8086
        elif condition == 3:
            config(p, 6, 0x1001, MASK, 1, 1)  # R does not imply X
        elif condition == 4:
            config(p, 6, 0x1001, 0x3003, 1, 4)
        elif condition == 5:
            p.emit(custom(0x2b, 3))
        elif condition == 6:
            start = 0x3ffd
            p.mem[0x10ffe:0x11000] = bytes([0x24, 0])
        elif condition == 7:
            start = MASK
            config(p, 6, 0x4001, MASK, 1, 4)
            p.mem[0x10000] = 0x24
        elif condition == 8:
            config(p, 1, 0x4000, 0x10003)  # data proof only
            config(p, 1, 0x4000, 0x10000, k=1)  # revoke X
        elif condition == 9:
            config(p, 4, 0x10000, 0x18000)  # identical bounds flush proofs
        calculate(p, expected, 0x84, start, 0xdeadbeef, MASK)
        reads = [0x10000] if condition in (4, 7) else [0x10ffc] if condition == 6 else []
        finish(f"xea_reject_{condition}", p, expected, reads=reads)

    for phase in range(5):
        p, expected = setup(), {}
        size, raw, start, bad = SIZE, 0x84, 0x3000, 0
        p.mem[0x10001:0x10006] = bytes([0x24, 1, 2, 3, 4])
        if phase == 0:
            size, bad = 0x10000, 0x10001  # SIB read
        elif phase == 1:
            size, bad = 0x10004, 0x10002  # second displacement beat
        elif phase == 2:
            p.li(9, 0x30000); p.emit(custom(0x7b, 2, a=9))
            raw, start, bad = 0, 0, 0x30000  # first GPR
        elif phase == 3:
            p.li(9, 0x1fffc); p.emit(custom(0x7b, 2, a=9))
            p.mem[0x10001] = 0x08
            raw, bad = 4, 0x20000  # index after a successful base read
        else:
            size, raw, bad = 0x10000, 5, 0x10001  # displacement without SIB
        p.li(10, raw); p.li(11, start); p.li(12, 0xdeadbeef)
        p.emit(custom(0x7b, 0, 12, 10, 11))
        p.emit(st(2, 0, 12, 0))  # younger store must not issue
        finish(f"xea_native_fault_{phase}", p, expected, size=size, trap=(5, bad))

    invalid = [(custom(0x7b, 0, 12, 10, 11), raw, 0x8000) for raw in (0xc0, 0x100, MASK)]
    invalid += [(custom(0x7b, 0, 12, 10, 11, 1), 0, 0x8000),
                (custom(0x7b, 1, 13, 1), 0, 0x8000),
                (custom(0x7b, 1, 13, 0, 1), 0, 0x8000),
                (custom(0x7b, 1, 13, k=1), 0, 0x8000),
                (custom(0x7b, 2, 1, 9), 0, 0x8000),
                (custom(0x7b, 2, 0, 9, 1), 0, 0x8000),
                (custom(0x7b, 2, 0, 9, k=1), 0, 0x8000),
                (custom(0x7b, 2, 0, 9), 0, 0x8001),
                (custom(0x7b, 2, 0, 9), 0, 0xfffffffc)]
    for n, (word, raw, pointer) in enumerate(invalid):
        p, expected = setup(), {}
        p.li(9, pointer); p.li(10, raw); p.li(11, 0x3000)
        p.emit(word, st(2, 0, 10, 0))
        finish(f"xea_illegal_{n}", p, expected, trap=(2, word), reads=[])

    p, expected = setup(), {}
    p.li(31, 0x4000); p.emit(custom(0x7b, 4, a=31))
    expect(p, expected, custom(0x7b, 1, 13), 0)
    p.finish(); p.pc = 0x4000
    calculate(p, expected, 0, MASK, values[0], 0)
    p.emit(custom(0x7b, 5))
    finish("xea_banks_share_pointer_info", p, expected, bank_only=True)
    return result


def jit_isa_cases():
    """New data/control operations under aliases, stalls, faults and both banks."""
    result = []

    def status(p):
        p.li(30, 0x801)
        p.emit(it(0x0b, 0, 4, 30, 0), 0x0000000b) # committed=801, pending=44

    def finish(p):
        p.emit(it(0x0b, 26, 5, 0, 0), it(0x0b, 27, 6, 0, 0), it(0x0b, 28, 5, 0, 0))
        return p.finish()

    p = Program()
    status(p)
    for lane, high in ((0, 0), (1, 0), (2, 0), (2, 1), (3, 0), (3, 1)):
        for a, b in ((1, 2), (1, 1), (0, 2), (1, 0)):
            for rd in (0, 1, 2, 3):
                for source in (0, MASK, 0x807fff01):
                    p.li(1, 0xa593c76e); p.li(2, source); p.li(3, 0x12345678)
                    p.emit(0x0b | rd << 7 | lane << 12 | a << 15 | b << 20 | (64 | high << 4) << 25)
    result.append(("xmerge_lanes_aliases_flags", finish(p), -1, False))

    p = Program()
    status(p)
    for shift in (1, 2, 3):
        for a, b in ((1, 2), (1, 1), (0, 2), (1, 0)):
            for rd in (0, 1, 2, 3):
                for source in (0, 1, 0x80000000, MASK, 0xf2345678):
                    p.li(1, source); p.li(2, 0x87654321)
                    p.emit(rt(rd, shift * 2, a, b, 16))
    result.append(("zba_aliases_wrapping_flags", finish(p), -1, False))

    p = Program()
    for combination in range(64):
        flags = sum(((combination >> n) & 1) << bit for n, bit in enumerate((0, 2, 4, 6, 7, 11)))
        p.li(1, flags); p.emit(it(0x0b, 0, 4, 1, 0), 0x0000000b)
        for cc in range(16):
            p.emit(it(0x13, 2, 0, 0, 0), xjcc(cc, 8), it(0x13, 2, 0, 0, 1))
    result.append(("xjcc_all_conditions", finish(p), -1, False))

    p = Program()
    p.li(1, 3)
    loop = p.pc
    p.emit(it(0x13, 1, 0, 1, -1), 0x0b | 1 << 15 | 13 << 25) # CMP x1,0, commit
    p.emit(xjcc(5, loop - p.pc))
    p.emit(xjcc(5, 2)) # untaken, misaligned unused target
    result.append(("xjcc_backward_untaken_alignment", p.finish(), -1, False))

    for off in (-4096, 4092):
        p = Program()
        status(p)
        target = p.pc + off
        p.emit(xjcc(0, off), st(2, 0, 1, 0)) # OF=1; younger store must not issue
        p.pc = target
        result.append((f"xjcc_offset_{off}", p.finish(), -1, False))
    p = Program()
    p.emit(jal(0, -0x1000))
    p.pc = 0
    p.emit(xjcc(1, -4)) # reset OF=0, wraps to fffffffc, next fetch faults
    result.append(("xjcc_wrapping_fetch_fault", bytes(p.mem), -1, False))

    invalid = [xjcc(16, 2), xjcc(4, 2) | 1 << 20]
    invalid += [0x0b | lane << 12 | control << 25
                for lane, control in ((0, 80), (1, 80), (2, 65), (3, 72), (2, 96))]
    invalid += [rt(0, f, 0, 0, 16) for f in (0, 1, 3, 5, 7)]
    for n, word in enumerate(invalid):
        p = Program()
        status(p)
        p.emit(word, st(2, 0, 30, 0))
        result.append((f"jit_isa_illegal_{n}", p.finish(), -1, False))
    p = Program()
    status(p)
    p.emit(xjcc(0, 2), st(2, 0, 30, 0))
    result.append(("xjcc_taken_alignment", p.finish(), -1, False))

    p = Program()
    status(p)
    p.li(31, 0x4000); p.emit(it(0x7b, 0, 4, 31, 0))
    p.emit(it(0x7b, 5, 6, 3, 0))
    finish(p)
    p.pc = 0x4000
    p.li(1, 0xa593c76e); p.li(2, 0x807fff01)
    p.emit(0x0b | 3 << 7 | 3 << 12 | 1 << 15 | 2 << 20 | 64 << 25,
           rt(3, 4, 3, 2, 16), xjcc(0, 8), st(2, 0, 3, 0), it(0x7b, 0, 5, 0, 0))
    result.append(("jit_isa_bank1_flags_preserved", bytes(p.mem), -1, True))
    return result


def cases():
    rng = random.Random(0x8632)
    result = []
    result.extend(tlb_cases())
    result.extend(guest_memory_cases())
    result.extend(ea_cases())
    result.extend(jit_isa_cases())
    # All generated operands/forms are checked against the Rust gold ISS below,
    # before their independently calculated event stream is compared with RTL.
    edges = [0, 1, 15, 16, 0x7f, 0x80, 0xff, 0x7fff, 0x8000, 0xffff, 0x7fffffff, 0x80000000, MASK]
    pairs = [(a, b) for a, b in zip(edges, reversed(edges))]
    pairs += [(rng.getrandbits(32), rng.getrandbits(32)) for _ in range(48)]
    for lane in range(4):
        p = Program()
        for kind in range(8):
            for cf in (0, 1):
                for n, (a, b) in enumerate(pairs):
                    p.li(1, a); p.li(2, b); p.li(4, 0xfffff72a | cf)
                    p.emit(it(0x0b, 0, 4, 4, 0))
                    ctl = kind | (8 if n & 1 else 0)
                    if kind in (0, 5) and n & 2:
                        ctl |= 32
                    if lane >= 2 and kind != 7 and n & 4:
                        ctl |= 16
                    dst = n % 4
                    word = 0x0b | dst << 7 | lane << 12 | 1 << 15 | (0 if kind == 7 else 2) << 20 | ctl << 25
                    p.emit(word, it(0x0b, 5, 5, 4, 0), it(0x0b, 6, 7, n % 16, 0),
                           it(0x0b, 7, 6, dst, 0), it(0x0b, 8, 5, 4, 0))
        result.append((f"xflags_lane{lane}", p.finish(), -1, False))
    p = Program()
    for combination in range(64):
        flags = sum(((combination >> n) & 1) << bit for n, bit in enumerate((0, 2, 4, 6, 7, 11)))
        p.li(1, flags); p.emit(it(0x0b, 0, 4, 1, 0))
        for cc in range(16):
            p.emit(it(0x0b, 2, 7, cc, 0))
    result.append(("xflags_conditions", p.finish(), -1, False))
    p = Program()
    p.li(1, 0x203); p.emit(it(0x0b, 0, 4, 1, 0))
    p.li(31, 0x4000); p.emit(it(0x7b, 0, 4, 31, 0))
    p.emit(it(0x0b, 2, 5, 1, 0), it(0x0b, 0, 6, 0, 0), it(0x0b, 3, 5, 1, 0))
    p.finish(); p.pc = 0x4000
    p.emit(0x0000000b, it(0x7b, 0, 5, 0, 7))
    result.append(("xflags_bank_abort", bytes(p.mem), -1, True))
    p = Program()
    for reg in range(1, 32):
        p.li(reg, rng.getrandbits(32))
    p.emit(it(0x13, 0, 0, 1, 1))
    for _ in range(700):
        rd, a, b, f3 = rng.randrange(32), rng.randrange(32), rng.randrange(32), rng.randrange(8)
        if rng.randrange(2):
            f7 = rng.choice((0, 1, 32)) if f3 in (0, 5) else rng.choice((0, 1))
            p.emit(rt(rd, f3, a, b, f7))
        else:
            imm = rng.randrange(4096)
            if f3 in (1, 5):
                imm = rng.randrange(32) | (0x400 if f3 == 5 and rng.randrange(2) else 0)
            p.emit(it(0x13, rd, f3, a, imm))
    p.emit(0x12345297)  # AUIPC
    result.append(("alu", p.finish(), -1, False))

    p = Program()
    edges = (0, 1, 2, 0x7fffffff, 0x80000000, 0x80000001, 0xfffffffe, MASK)
    pairs = [(a, b) for a in edges for b in edges]
    pairs += [(rng.getrandbits(32), rng.getrandbits(32)) for _ in range(128)]
    for a, b in pairs:
        p.li(1, a); p.li(2, b)
        for op in range(8):
            p.emit(rt(3, op, 1, 2, 1), rt(4, 0, 3, 3))
    result.append(("muldiv", p.finish(), -1, False))

    p = Program()
    p.li(1, 0x18000); p.li(2, 0x80ff81fe)
    p.emit(st(2, 1, 2, 0), it(0x03, 0, 2, 1, 0))
    for off in range(4):
        p.emit(it(0x03, 3, 0, 1, off), it(0x03, 4, 4, 1, off), st(0, 1, 2, off))
    for off in (0, 2):
        p.emit(it(0x03, 3, 1, 1, off), it(0x03, 4, 5, 1, off), st(1, 1, 2, off))
    for _ in range(120):
        width = rng.randrange(3)
        off = rng.randrange(32) << width
        p.li(2, rng.getrandbits(32))
        p.emit(st(width, 1, 2, off), it(0x03, 5, width, 1, off))
    p.emit(0x0ff0000f, 0x0000100f)  # FENCE, FENCE.I
    result.append(("memory", p.finish(), -1, False))

    p = Program()
    p.li(1, MASK); p.li(2, 1); p.li(3, 0)
    for f3 in (0, 1, 4, 5, 6, 7):
        for a, b in ((1, 2), (2, 1), (1, 1)):
            p.emit(br(f3, a, b, 8), it(0x13, 3, 0, 3, 1))
    p.emit(jal(4, 8), 0xffffffff)
    target = p.pc + 16
    p.li(5, target | 1)
    p.emit(it(0x67, 6, 0, 5, 0), 0xffffffff)
    p.li(7, 12)
    p.emit(it(0x13, 7, 0, 7, -1), br(1, 7, 0, -4))
    # Not-taken misaligned branch must not fault.
    p.emit(br(0, 1, 2, 2))
    result.append(("flow", p.finish(), -1, False))

    p = Program()
    for r in range(1, 32):
        p.li(r, r*37)
        p.emit(it(0x7b, r, 7, r, 0))
    p.emit(it(0x7b, 0, 7, 1, 0))  # inactive x0 ignores write
    p.li(31, 0x4000)
    for _ in range(3):
        p.emit(it(0x7b, 0, 4, 31, 0))
        for r in range(31):
            p.emit(it(0x7b, 30, 6, r, 0))
        for selector in range(3):
            p.emit(it(0x7b, 29, 6, selector, 32))
    p.finish()
    p.pc = 0x4000
    p.emit(it(0x13, 1, 0, 1, 1), rt(16, 0, 1, 2, 1))
    p.li(17, 0x18000)
    p.emit(st(2, 17, 16, 0), it(0x03, 18, 2, 17, 0), rt(19, 0, 18, 16))
    p.emit(it(0x7b, 0, 5, 0, 7), 0xffffffff)
    result.append(("banking", bytes(p.mem), -1, True))

    # Store is delayed while the frontend may fetch the old target word. FENCE.I
    # must discard that word and refetch the newly written instruction.
    p = Program()
    target = 0x1018
    p.li(1, target); p.li(2, it(0x13, 3, 0, 0, 99))
    p.emit(st(2, 1, 2, 0), 0x100f, it(0x13, 3, 0, 0, 11))
    result.append(("fence_i_patch", p.finish(), -1, False))

    # Decode, target alignment and access faults must not produce GPR/store effects.
    invalid = [0xffffffff, 0x30001073, it(0x13, 2, 1, 1, 0x20),
               rt(2, 1, 1, 1, 32), it(0x03, 2, 3, 1, 0), st(4, 1, 1, 0),
               it(0x67, 2, 1, 1, 0), br(2, 1, 1, 4),
               it(0x7b, 0, 5, 0, 0), it(0x7b, 1, 6, 3, 32), xjcc(16, 0),
               it(0x0b, 1, 4, 1, 0), it(0x0b, 2, 5, 1, 1),
               it(0x0b, 2, 7, 16, 0), 0x8200000b, 0x2000100b,
               0x4200000b, 0x0e10000b]
    endings = [(f"illegal_{n}", word) for n, word in enumerate(invalid)]
    endings += [("load_align", it(0x03, 2, 2, 1, 1)),
                ("store_align", st(1, 1, 1, 1)), ("load_fault", it(0x03, 0, 2, 1, 0)),
                ("store_fault", st(2, 1, 1, 0)), ("jal_align", jal(2, 2)),
                ("jalr_align", it(0x67, 2, 0, 1, 2)),
                ("branch_align", br(0, 1, 1, 2)), ("ecall", 0x73)]
    for name, word in endings:
        p = Program()
        p.li(1, SIZE)
        p.emit(word, st(2, 0, 1, 0))  # younger store must never execute
        result.append((name, p.finish(), -1, False))
    p = Program()
    p.emit(it(0x13, 1, 0, 0, 1), it(0x13, 2, 0, 1, 2))
    result.append(("fetch_fault", p.finish(), 0x1004, False))
    for name, word in (("load", it(0x03, 0, 2, 1, 0)), ("store", st(2, 1, 2, 0))):
        p = Program()
        p.li(1, 0x18000); p.li(2, 0x12345678)
        fault_pc = p.pc
        p.emit(word)
        result.append((f"fetch_fault_{name}", p.finish(), fault_pc, False))
    # A failing sequential fetch younger than a taken jump must be discarded.
    p = Program()
    p.emit(jal(1, 8), 0xffffffff, it(0x13, 2, 0, 1, 1))
    result.append(("wrong_path_fetch_fault", p.finish(), 0x1004, False))
    p = Program()
    p.li(1, SIZE)
    p.emit(it(0x67, 0, 0, 1, 0))
    result.append(("fetch_unmapped", p.finish(), -1, False))
    p = Program()
    p.li(1, 0x4000)
    p.emit(it(0x7b, 0, 4, 1, 0))
    p.finish()
    p.pc = 0x4000
    p.emit(it(0x7b, 0, 4, 0, 0))
    result.append(("nested_entry", bytes(p.mem), -1, True))
    p = Program()
    p.li(1, 0x4002)
    p.emit(it(0x7b, 0, 4, 1, 0))
    result.append(("entry_align", p.finish(), -1, True))
    return result


def rust_image():
    elf = OUT / "native.elf"
    run(["rustc", "--edition=2024", "--target=riscv32im-unknown-none-elf",
         "-C", "opt-level=2", "-C", "panic=abort", "-C", "relocation-model=static",
         "-C", f"link-arg=-T{RTL / 'tests/link.ld'}", RTL / "tests/native.rs", "-o", elf])
    blob = elf.read_bytes()
    assert blob[:6] == b"\x7fELF\x01\x01"
    phoff = struct.unpack_from("<I", blob, 28)[0]
    phsize, phnum = struct.unpack_from("<HH", blob, 42)
    mem = bytearray(SIZE)
    for n in range(phnum):
        kind, offset, addr, _, filesz, memsz, _, _ = struct.unpack_from("<8I", blob, phoff+n*phsize)
        if kind == 1:
            assert addr + memsz < SIZE
            mem[addr:addr+filesz] = blob[offset:offset+filesz]
    rng = random.Random(132)
    for n in range(80):
        struct.pack_into("<I", mem, 0x1e000 + n*4, rng.getrandbits(32))
    # Check an application-level signature independently of instruction stepping.
    values = struct.unpack_from("<80I", mem, 0x1e000)
    total = 0x01234567
    for n in range(40):
        a, b = values[n], values[n+40] | 1
        mix = ((a*b >> 32) ^ a*b ^ a//b ^ a%b ^
               multiply_divide(4, a, b) ^ multiply_divide(6, a, b)) & MASK
        total = ((total << 3 | total >> 29) ^ mix) & MASK
    _, final = reference(mem, 2)
    assert struct.unpack_from("<I", final, 0x1e000+127*4)[0] == total
    (OUT / "native.objdump").write_text(run(["llvm-objdump", "-d", elf]))
    return bytes(mem), total


def main():
    global OUT, SIMULATOR
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--synth", action="store_true")
    parser.add_argument("--gowin", action="store_true", help="also implies --synth")
    parser.add_argument("--out", type=Path, default=OUT)
    parser.add_argument("--simulator", type=Path, help="use this pinned gold ISS without rebuilding")
    parser.add_argument("--yosys-data", type=Path,
                        default=Path(shutil.which("yosys") or "/usr/bin/yosys")
                        .resolve().parent.parent / "share/yosys")
    args = parser.parse_args()
    OUT = args.out.resolve()
    if args.simulator:
        SIMULATOR = args.simulator.resolve()
    OUT.mkdir(parents=True, exist_ok=True)
    if not args.simulator:
        run(["cargo", "build", "--release", "--no-default-features", "--features", "r86chip", "--bin", "r86chip-sim"], ROOT)
    programs = cases()
    image, signature = rust_image()
    programs.append(("rust", image, -1, False))
    # Qualify software consumers on the gold ISS before touching RTL results.
    # The bank-count and injected-fetch-error harness variants stay explicit.
    for name, image, fault_pc, bank_only in programs:
        image_path = OUT / f"{name}.hex"
        image_path.write_text("\n".join(f"{b:02x}" for b in image) + "\n")
        image_path.with_suffix(".bin").write_bytes(image)
        if fault_pc < 0:
            expected, final_memory = reference(image, 2)
            compare_iss(image_path, expected, final_memory)
    print(f"ISS passed: {len(programs)} native fixtures. Generating Chisel and building simulations...", flush=True)
    build()
    rows = []
    for name, image, fault_pc, bank_only in programs:
        image_path = OUT / f"{name}.hex"
        for banks in (1, 2):
            # Exercise the same banking binary on BANKS=1: it must trap, not alias.
            expected, final_memory = reference(image, banks, fault_pc)
            # Icarus adds a four-state run: Verilator's two-state RAM startup
            # must not hide accidental dependence on uninitialized RF contents.
            schedules = (("verilator", 1, 0), ("verilator", 2, 7),
                         ("verilator", 0x8632, 7), ("iverilog", 0x8632, 7))
            for engine, seed, latency in schedules:
                executable = ([OUT / f"b{banks}/obj/Vcore_tb"] if engine == "verilator"
                              else ["vvp", OUT / f"b{banks}/core.vvp"])
                log = run([*executable, f"+IMAGE={image_path}",
                           f"+SEED={seed}", f"+LATENCY={latency}", f"+FAULT_PC={fault_pc & MASK:x}",
                           f"+RAM_BYTES={len(image)}"])
                (OUT / f"{name}-b{banks}-{engine}-s{seed}.log").write_text(log)
                actual = [(line[0], *[int(v, 16) for v in line.split()[1:]])
                          for line in log.splitlines() if line.startswith(("R ", "D ", "S ", "T "))]
                if actual != expected:
                    for n in range(max(len(actual), len(expected))):
                        got = actual[n] if n < len(actual) else None
                        want = expected[n] if n < len(expected) else None
                        if got != want:
                            raise AssertionError(f"{name} banks={banks} {engine} seed={seed} event={n}\n"
                                                 f"got {got}\nexpected {want}")
                count = next(line for line in log.splitlines() if line.startswith("C "))
                cycles, retired, stores, pending, stalls = map(int, count.split()[1:])
                rows.append(dict(case=name, banks=banks, simulator=engine, seed=seed, latency=latency,
                                 cycles=cycles, retired=retired, stores=stores,
                                 redirects_with_pending_fetch=pending, data_stall_cycles=stalls))
    assert sum(r["redirects_with_pending_fetch"] for r in rows) > 0
    assert sum(r["data_stall_cycles"] for r in rows) > 0
    print(f"Simulation passed: {len(rows)} runs", flush=True)
    mapped, library_report = [], None
    if args.synth or args.gowin:
        print("Checking Yosys structure" + (" and mapping GW5A..." if args.gowin else "..."), flush=True)
        library = mapper = None
        if args.gowin:
            from rf_probe import prepare_library
            library, mapper, library_report = prepare_library(args.yosys_data.resolve(), OUT)
        mapped = [synthesize(b, args.gowin, args.yosys_data.resolve(), library, mapper) for b in (1, 2)]
    inputs = [RTL / "build.sbt", RTL / "project/build.properties", RTL / "r86_regfile.v",
              *sorted((RTL / "src").rglob("*.scala")), *sorted((RTL / "tests").glob("*")),
              Path(__file__), HERE / "rf_probe.py", HERE.parent / "sim/rv32.rs",
              HERE.parent / "sim/native.rs", HERE.parent / "sim/memory.rs"]
    report = dict(scope="Native RV32, arithmetic/status, fresh-byte effective addresses, guest memory/context and same-bank software service; no full interpreter integration or caches",
                  isa_identity="42310008",
                  simulator=dict(path=str(SIMULATOR), sha256=hashlib.sha256(SIMULATOR.read_bytes()).hexdigest()),
                  simulations=len(rows), cases=len(programs), rust_signature=f"{signature:08x}",
                  verilator=run(["verilator", "--version"]).strip(),
                  iverilog=run(["iverilog", "-V"]).splitlines()[0],
                  yosys=run(["yosys", "-V"]).strip() if mapped else None,
                  java=run(["java", "-version"]).splitlines()[0],
                  rustc=run(["rustc", "--version"]).strip(),
                  chisel="7.12.0", scala="2.13.18", sbt="1.12.11", firtool="1.146.0",
                  sources={str(p.relative_to(HERE.parent)): hashlib.sha256(p.read_bytes()).hexdigest()
                           for p in inputs},
                  emitted={str(p.relative_to(OUT)): hashlib.sha256(p.read_bytes()).hexdigest()
                           for b in (1, 2) for p in sources(b)[:2]},
                  library=library_report, synthesis=mapped, results=rows)
    (OUT / "report.json").write_text(json.dumps(report, indent=2) + "\n")
    print(f"PASS: {len(programs)} programs, {len(rows)} RTL/oracle runs; Rust signature {signature:08x}")
    print("Verilator execution/lint passed; " + ("generic synthesis/check passed" if mapped else "synthesis not requested"))
    for row in mapped:
        print(row)
    print(f"Report: {OUT / 'report.json'}")


if __name__ == "__main__":
    main()
